// mch-codegen — build-time MCH IR -> C++ source generator (no Python in the
// C++ build; the version-controlled IR JSON is the contract).
//
// Usage:
//   mch-codegen --vectors <expr_vectors.json> -o <out.cpp>
//   mch-codegen --wheres  <mch_ir.json>       -o <out.cpp>
//   mch-codegen --builds  <mch_ir.json | build_vectors.json> --suffix <sfx> -o <out.cpp>
//
// Every mode runs as a CMake custom command; outputs land in the build tree
// (<binary-dir>/generated/), never in the source tree or git.
// The `--vectors` mode emits the expression-conformance functions + table.
// The `--wheres` mode emits one function per artifact node carrying a
// `where_expr`, keyed by the global node index (consumed by --match-gen).
// The `--builds` mode emits one BuildOutcome fn per matcher with a
// build_program; `--suffix` names the table symbols (gen_builds_<sfx>) so the
// ir-artifact table and the build-vectors table link into one binary, each
// permanently paired with its own input document.
#include "ExprCodegen.h"

#include "td/utils/JsonBuilder.h"
#include "td/utils/crypto.h"

#include <cstdio>
#include <fstream>
#include <sstream>
#include <string>

namespace {

const char *kVectorsHeader =
    "// GENERATED by mch-codegen (ton-mch-engine/codegen) - DO NOT EDIT BY HAND.\n"
    "//\n"
    "// One `EvalResult vec_<i>(const Env&, const Lookups&)` per expression\n"
    "// conformance vector (ir/expr_vectors.json), plus the gen_vectors() table\n"
    "// consumed by `ton-mch-engine --vectors-gen`. Regenerated automatically by\n"
    "// the CMake build (build-tree output; not in git).\n";

const char *kWheresHeader =
    "// GENERATED by mch-codegen (ton-mch-engine/codegen) - DO NOT EDIT BY HAND.\n"
    "//\n"
    "// One `EvalResult where_<node_id>(const WhereEnv&)` per artifact node carrying\n"
    "// a `where_expr`, plus the gen_wheres() table consumed by\n"
    "// `ton-mch-engine --match-gen`. node_id == the ARTIFACT-GLOBAL node index.\n"
    "// Regenerated automatically by the CMake build from ir/mch_ir.json\n"
    "// (build-tree output; not in git).\n";

const char *kBuildsHeader =
    "// GENERATED by mch-codegen (ton-mch-engine/codegen) - DO NOT EDIT BY HAND.\n"
    "//\n"
    "// One `BuildOutcome build_<id>(BuildEnv&)` per matcher with a build_program\n"
    "// (or per build-vector case), plus a gen_builds_<suffix>() table (ir: the\n"
    "// classify/build-smoke loops; vectors: `ton-mch-engine --build-vectors`).\n"
    "// Regenerated automatically by the CMake build from its input document\n"
    "// (build-tree output; not in git).\n";

int fail(const std::string &msg) {
  std::fprintf(stderr, "mch-codegen: %s\n", msg.c_str());
  return 2;
}

}  // namespace

int main(int argc, char *argv[]) {
  std::string vectors_path;
  std::string wheres_path;
  std::string builds_path;
  std::string suffix;
  std::string out_path;
  for (int i = 1; i < argc; i++) {
    std::string a = argv[i];
    if (a == "--vectors" && i + 1 < argc) {
      vectors_path = argv[++i];
    } else if (a == "--wheres" && i + 1 < argc) {
      wheres_path = argv[++i];
    } else if (a == "--builds" && i + 1 < argc) {
      builds_path = argv[++i];
    } else if (a == "--suffix" && i + 1 < argc) {
      suffix = argv[++i];
    } else if ((a == "-o" || a == "--output") && i + 1 < argc) {
      out_path = argv[++i];
    } else {
      return fail("unexpected argument '" + a + "'");
    }
  }
  const int n_modes = static_cast<int>(!vectors_path.empty()) + static_cast<int>(!wheres_path.empty()) +
                      static_cast<int>(!builds_path.empty());
  const std::string in_path =
      !vectors_path.empty() ? vectors_path : (!wheres_path.empty() ? wheres_path : builds_path);
  if (in_path.empty() || out_path.empty() || n_modes != 1) {
    return fail(
        "usage: mch-codegen (--vectors <expr_vectors.json> | --wheres <mch_ir.json> | "
        "--builds <mch_ir.json|build_vectors.json> --suffix <sfx>) -o <out.cpp>");
  }
  if (!builds_path.empty() && suffix.empty()) {
    return fail("--builds requires --suffix <sfx> (names the gen_builds_<sfx> table symbols)");
  }
  if (builds_path.empty() && !suffix.empty()) {
    return fail("--suffix is only valid with --builds");
  }

  std::ifstream in(in_path, std::ios::binary);
  if (!in) {
    return fail("cannot open " + in_path);
  }
  std::stringstream ss;
  ss << in.rdbuf();
  std::string buf = ss.str();  // must outlive the decoded tree (Slices point in)

  // Source identity, hashed BEFORE json_decode mutates the buffer. Emitted
  // into the generated table so runners can hard-fail on a wrong pairing.
  std::string source_sha;
  {
    unsigned char digest[32];
    td::sha256(td::Slice(buf), td::MutableSlice(digest, 32));
    static const char *hex = "0123456789abcdef";
    for (int i = 0; i < 32; i++) {
      source_sha += hex[digest[i] >> 4];
      source_sha += hex[digest[i] & 0xF];
    }
  }

  auto r_root = td::json_decode(td::MutableSlice(buf));
  if (r_root.is_error()) {
    return fail("json parse error: " + r_root.error().message().str());
  }
  td::JsonValue root = r_root.move_as_ok();

  std::string src;
  try {
    if (!vectors_path.empty()) {
      src = mch_codegen::generate_vectors_file(root, kVectorsHeader);
    } else if (!wheres_path.empty()) {
      src = mch_codegen::generate_wheres_file(root, kWheresHeader, source_sha);
    } else {
      src = mch_codegen::generate_builds_file(root, kBuildsHeader, source_sha, suffix);
    }
  } catch (const std::exception &e) {
    return fail(std::string("codegen failed: ") + e.what());
  }

  // Write with LF newlines regardless of platform (binary mode).
  std::ofstream out(out_path, std::ios::binary);
  if (!out) {
    return fail("cannot write " + out_path);
  }
  out.write(src.data(), static_cast<std::streamsize>(src.size()));
  std::fprintf(stderr, "mch-codegen: wrote %s\n", out_path.c_str());
  return 0;
}
