// mch-codegen — build-time MCH IR -> C++ source generator (no Python in the
// C++ build; the version-controlled IR JSON is the contract).
//
// Usage:
//   mch-codegen --vectors <expr_vectors.json> -o <out.cpp>
//   mch-codegen --wheres  <mch_ir.json> --suffix <sfx> -o <out.cpp>
//   mch-codegen --builds  <mch_ir.json | build_vectors.json> --suffix <sfx> -o <out.cpp>
//   mch-codegen --matchers <mch_ir.json> --suffix <sfx> -o <out.cpp>
//
// Every mode runs as a CMake custom command; outputs land in the build tree
// (<binary-dir>/generated/), never in the source tree or git.
//
// TODO: remove (harness): of the artifact-driven modes, `--vectors` is the only
// TEST-ONLY one — its table lives in mch-fixtures (GenVectors.h), as does the
// `--builds ir/build_vectors.json --suffix vectors` table
// (fixtures/GenBuildsVectors.h). `--wheres` and `--builds` over ir/mch_ir.json
// both feed PRODUCTION (gen_wheres_ir / gen_builds_ir — the tables ClassifyCore
// runs). Keep that split in mind before adding a mode: a new mode is production
// only if a mch-classify TU references its symbols.
// The `--vectors` mode emits the expression-conformance functions + table.
// The `--wheres` mode emits one function per artifact node carrying a
// `where_expr`, keyed by the global node index.
// The `--matchers` mode emits the whole CompiledMatcher table as C++ data — the
// mode that took the IR document off the production binaries' startup surface.
// The `--wheres` / `--builds` modes both take `--suffix`, which names the table
// symbols (gen_wheres_<sfx> / gen_builds_<sfx>) so the tables of several input
// documents link into one binary, each permanently paired with its own document
// (ir artifact, build vectors, testbed artifact) and selected at run time by
// source sha.
#include "ExprCodegen.h"
#include "MatcherCodegen.h"

#include "td/utils/JsonBuilder.h"
#include "td/utils/crypto.h"

#include <cstdio>
#include <fstream>
#include <sstream>
#include <string>

namespace {

const char *kVectorsHeader =
    "// GENERATED by mch-codegen (ton-mch-engine/codegen) - DO NOT EDIT BY HAND.\n"
    "//\n"
    "// One `EvalResult vec_<i>(const Env&, const Lookups&)` per expression\n"
    "// conformance vector (ir/expr_vectors.json), plus the gen_vectors() table\n"
    "// consumed by `ton-mch-engine --vectors-gen`. Regenerated automatically by\n"
    "// the CMake build (build-tree output; not in git).\n";

const char *kWheresHeader =
    "// GENERATED by mch-codegen (ton-mch-engine/codegen) - DO NOT EDIT BY HAND.\n"
    "//\n"
    "// One `EvalResult where_<node_id>(const WhereEnv&)` per artifact node carrying\n"
    "// a `where_expr`, plus a gen_wheres_<suffix>() table — the where evaluator the\n"
    "// matcher walker runs (ir: production classify). node_id == the\n"
    "// ARTIFACT-GLOBAL node index. Regenerated automatically by the CMake build\n"
    "// from its input document (build-tree output; not in git).\n";

const char *kMatchersHeader =
    "// GENERATED by mch-codegen (ton-mch-engine/codegen) - DO NOT EDIT BY HAND.\n"
    "//\n"
    "// The whole CompiledMatcher table of an IR artifact as C++ data (one\n"
    "// `mk_<i>()` builder per matcher, in priority order), behind a\n"
    "// gen_matchers_<suffix>() accessor — the match phase's input. Production\n"
    "// parses NO artifact at run time; this table is generated from the document\n"
    "// by the CMake build (build-tree output; not in git).\n";

const char *kBuildsHeader =
    "// GENERATED by mch-codegen (ton-mch-engine/codegen) - DO NOT EDIT BY HAND.\n"
    "//\n"
    "// One `BuildOutcome build_<id>(BuildEnv&)` per matcher with a build_program\n"
    "// (or per build-vector case), plus a gen_builds_<suffix>() table (ir: the\n"
    "// classify/build-smoke loops; vectors: `ton-mch-engine --build-vectors`).\n"
    "// Regenerated automatically by the CMake build from its input document\n"
    "// (build-tree output; not in git).\n";

int fail(const std::string &msg) {
  std::fprintf(stderr, "mch-codegen: %s\n", msg.c_str());
  return 2;
}

// Write with LF newlines regardless of platform (binary mode).
int write_output(const std::string &out_path, const std::string &src) {
  std::ofstream out(out_path, std::ios::binary);
  if (!out) {
    return fail("cannot write " + out_path);
  }
  out.write(src.data(), static_cast<std::streamsize>(src.size()));
  std::fprintf(stderr, "mch-codegen: wrote %s\n", out_path.c_str());
  return 0;
}

// Escape-hardening self-test (§8.7): the string-literal emitter must render
// EVERY control byte safely and adjacency-proof. A known past bug emitted a raw
// NUL; a naive `\x` escape also mis-parses before an adjacent hex digit.
int run_selftest() {
  int failures = 0;
  auto expect = [&](const std::string &name, const std::string &got, const std::string &want) {
    if (got != want) {
      std::fprintf(stderr, "FAIL %s: got %s want %s\n", name.c_str(), got.c_str(), want.c_str());
      failures++;
    }
  };
  using mch_codegen::cstr;
  expect("plain", cstr("abc"), "\"abc\"");
  expect("quote_backslash", cstr("a\"b\\c"), "\"a\\\"b\\\\c\"");
  expect("named_ctrl", cstr("a\nb\tc\rd"), "\"a\\nb\\tc\\rd\"");
  // NUL followed by an ASCII digit: octal keeps them separate (\000 then '7').
  expect("nul_then_digit", cstr(std::string("\0" "7", 2)), "\"\\0007\"");
  // Bare NUL and other low control bytes -> 3-digit octal.
  expect("bare_nul", cstr(std::string("\0", 1)), "\"\\000\"");
  expect("byte_0x01", cstr(std::string("\x01", 1)), "\"\\001\"");
  expect("byte_0x1f", cstr(std::string("\x1f", 1)), "\"\\037\"");
  expect("del_0x7f", cstr(std::string("\x7f", 1)), "\"\\177\"");
  // Bytes >= 0x20 (and < 0x7f) pass through unescaped.
  expect("high_printable", cstr("~ "), "\"~ \"");
  std::fprintf(stderr, "mch-codegen selftest: %s\n", failures == 0 ? "ALL PASS" : "FAILURES");
  return failures == 0 ? 0 : 1;
}

}  // namespace

int main(int argc, char *argv[]) {
  std::string vectors_path;
  std::string wheres_path;
  std::string builds_path;
  std::string matchers_path;
  std::string suffix;
  std::string out_path;
  for (int i = 1; i < argc; i++) {
    std::string a = argv[i];
    if (a == "--selftest") {
      return run_selftest();
    } else if (a == "--vectors" && i + 1 < argc) {
      vectors_path = argv[++i];
    } else if (a == "--wheres" && i + 1 < argc) {
      wheres_path = argv[++i];
    } else if (a == "--builds" && i + 1 < argc) {
      builds_path = argv[++i];
    } else if (a == "--matchers" && i + 1 < argc) {
      matchers_path = argv[++i];
    } else if (a == "--suffix" && i + 1 < argc) {
      suffix = argv[++i];
    } else if ((a == "-o" || a == "--output") && i + 1 < argc) {
      out_path = argv[++i];
    } else {
      return fail("unexpected argument '" + a + "'");
    }
  }
  const int n_modes = static_cast<int>(!vectors_path.empty()) + static_cast<int>(!wheres_path.empty()) +
                      static_cast<int>(!builds_path.empty()) +
                      static_cast<int>(!matchers_path.empty());
  const std::string in_path = !vectors_path.empty()
                                  ? vectors_path
                                  : (!wheres_path.empty()
                                         ? wheres_path
                                         : (!builds_path.empty() ? builds_path : matchers_path));
  if (in_path.empty() || out_path.empty() || n_modes != 1) {
    return fail(
        "usage: mch-codegen (--vectors <expr_vectors.json> | --wheres <mch_ir.json> --suffix "
        "<sfx> | --builds <mch_ir.json|build_vectors.json> --suffix <sfx> | --matchers "
        "<mch_ir.json> --suffix <sfx>) -o <out.cpp>");
  }
  if (!builds_path.empty() && suffix.empty()) {
    return fail("--builds requires --suffix <sfx> (names the gen_builds_<sfx> table symbols)");
  }
  if (!wheres_path.empty() && suffix.empty()) {
    return fail("--wheres requires --suffix <sfx> (names the gen_wheres_<sfx> table symbols)");
  }
  if (!matchers_path.empty() && suffix.empty()) {
    return fail("--matchers requires --suffix <sfx> (names the gen_matchers_<sfx> table symbols)");
  }
  if (!vectors_path.empty() && !suffix.empty()) {
    return fail("--suffix is not valid with --vectors");
  }

  // --matchers goes through the LOADER (mch-ir-load), which owns the whole
  // artifact->table compile step; this tool only prints its output, so there is
  // no second parser to keep in step. The other modes walk the JSON directly.
  if (!matchers_path.empty()) {
    auto r_ir = mch::load_ir(matchers_path);
    if (r_ir.is_error()) {
      return fail("cannot load IR artifact: " + r_ir.error().message().str());
    }
    std::string src;
    try {
      src = mch_codegen::generate_matchers_file(r_ir.move_as_ok(), kMatchersHeader, suffix);
    } catch (const std::exception &e) {
      return fail(std::string("codegen failed: ") + e.what());
    }
    return write_output(out_path, src);
  }

  std::ifstream in(in_path, std::ios::binary);
  if (!in) {
    return fail("cannot open " + in_path);
  }
  std::stringstream ss;
  ss << in.rdbuf();
  std::string buf = ss.str();  // must outlive the decoded tree (Slices point in)

  // Source identity, hashed BEFORE json_decode mutates the buffer. Emitted
  // into the generated table so runners can hard-fail on a wrong pairing.
  std::string source_sha;
  {
    unsigned char digest[32];
    td::sha256(td::Slice(buf), td::MutableSlice(digest, 32));
    static const char *hex = "0123456789abcdef";
    for (int i = 0; i < 32; i++) {
      source_sha += hex[digest[i] >> 4];
      source_sha += hex[digest[i] & 0xF];
    }
  }

  auto r_root = td::json_decode(td::MutableSlice(buf));
  if (r_root.is_error()) {
    return fail("json parse error: " + r_root.error().message().str());
  }
  td::JsonValue root = r_root.move_as_ok();

  std::string src;
  try {
    if (!vectors_path.empty()) {
      src = mch_codegen::generate_vectors_file(root, kVectorsHeader);
    } else if (!wheres_path.empty()) {
      src = mch_codegen::generate_wheres_file(root, kWheresHeader, source_sha, suffix);
    } else {
      src = mch_codegen::generate_builds_file(root, kBuildsHeader, source_sha, suffix);
    }
  } catch (const std::exception &e) {
    return fail(std::string("codegen failed: ") + e.what());
  }

  return write_output(out_path, src);
}
